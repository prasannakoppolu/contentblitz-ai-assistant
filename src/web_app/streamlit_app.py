"""ContentBlitz Streamlit app.

Run with:  streamlit run src/web_app/streamlit_app.py
Sections: Chat · Content Dashboard · Research Panel · Export · Settings (sidebar).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import streamlit as st  # noqa: E402
from langgraph.checkpoint.memory import MemorySaver  # noqa: E402

from src.core.config import load_settings  # noqa: E402
from src.core.workflow import ContentBlitzEngine  # noqa: E402
from src.web_app.components import chat, dashboard, export_panel, research_panel, settings_panel  # noqa: E402

st.set_page_config(page_title="ContentBlitz · AI Content Marketing", page_icon="⚡", layout="wide",
                   initial_sidebar_state="expanded")

css = Path(__file__).parent / "static" / "style.css"
if css.exists():
    st.markdown(f"<style>{css.read_text()}</style>", unsafe_allow_html=True)


def get_engine() -> ContentBlitzEngine:
    """(Re)build the engine when settings change; memory survives rebuilds."""
    ss = st.session_state
    ss.setdefault("checkpointer", MemorySaver())
    ss.setdefault("thread_id", ContentBlitzEngine.new_thread_id())
    signature = settings_panel.settings_signature()
    if ss.get("engine") is None or ss.get("engine_signature") != signature:
        settings = load_settings(overrides=settings_panel.settings_overrides())
        ss.engine = ContentBlitzEngine(settings, checkpointer=ss.checkpointer)
        ss.engine_signature = signature
    return ss.engine


def main() -> None:
    settings_panel.render_sidebar()
    engine = get_engine()
    state = engine.get_state(st.session_state.thread_id)

    st.markdown("<div class='cb-header'><h1>⚡ ContentBlitz</h1><p>Your multi-agent AI content marketing team: "
                "research → SEO blogs → LinkedIn posts → visuals.</p></div>", unsafe_allow_html=True)
    if engine.services.is_offline:
        st.info("Running in **offline demo mode** (no API keys detected or demo mode on). Content is generated by "
                "deterministic mock providers. Add keys in the sidebar for real GPT-4o / Claude / Gemini, SERP API / "
                "Perplexity and DALL-E output.", icon="🧪")

    tab_chat, tab_dash, tab_research, tab_export = st.tabs(["💬 Chat", "📝 Content Dashboard", "🔎 Research", "📦 Export"])
    with tab_chat:
        chat.render(engine, state)
    state = engine.get_state(st.session_state.thread_id)
    with tab_dash:
        dashboard.render(engine, state)
    with tab_research:
        research_panel.render(state)
    with tab_export:
        export_panel.render(state)


main()
